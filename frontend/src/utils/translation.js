// Search translation helper
export const translateSearchTerm = (term) => {
  if (!term) return term;
  
  const termLower = term.toLowerCase().trim();
  
  // Check if term is in Nepali and translate to English
  const nepaliToEnglishMap = {
    ...PROVINCE_TRANSLATIONS,
    ...DISTRICT_TRANSLATIONS,
    ...MUNICIPALITY_TRANSLATIONS
  };
  
  // Reverse map for English to Nepali
  const englishToNepaliMap = {};
  Object.entries(nepaliToEnglishMap).forEach(([nepali, english]) => {
    englishToNepaliMap[english.toLowerCase()] = nepali;
  });
  
  // Try to find translation
  if (nepaliToEnglishMap[termLower]) {
    return nepaliToEnglishMap[termLower];
  }
  
  if (englishToNepaliMap[termLower]) {
    return englishToNepaliMap[termLower];
  }
  
  return term;
};

// Get display name for field
export const getFieldDisplayName = (field) => {
  return ENGLISH_TO_NEPALI[field] || field;
};

// Get English field name from Nepali
export const getFieldFromNepali = (nepaliField) => {
  return FIELD_TRANSLATIONS[nepaliField] || nepaliField;
};

// Check if text is Nepali (contains Devanagari characters)
export const isNepaliText = (text) => {
  if (!text) return false;
  const devanagariRange = /[\u0900-\u097F]/;
  return devanagariRange.test(text);
};